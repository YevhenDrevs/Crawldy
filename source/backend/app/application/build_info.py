"""Чим саме є процес, який щойно відповів.

## Навіщо

`/health`, що віддає саме «ok», не відрізняє свіже розгортання від
процесу, який місяць виконує старий образ. Проєкт згаяв на цьому
чотири дні: автодеплой бекенду не спрацьовував, сервіс відповідав 200
на кожен запит, і ззовні це виглядало як робочий деплой — бо сервіс і
був робочий, просто не той. Щоб довести, який код виконується, довелося
читати тексти знахідок у звіті й порівнювати їх із репозиторієм.

## Чому відбитки, а не лише коміт

Коміт приходить зі змінної оточення: його може не бути, його може
поставити хостинг для образу, зібраного з іншого дерева, і він нічого
не каже про те, що всередині. Відбитки рахуються з САМОГО КОДУ — з
оголошень чеків і констант формули, — тож відповідають на питання «що
тут виконується» без жодної довіри до оточення.

Коміт лишається поруч, бо людині він зрозуміліший. Порожній рядок
означає «не знаємо», і це чесніше за вигадане значення.

## Чому тут, а не в маршруті

Шар API не ходить у двигун напряму — цю межу стереже
`test_the_debt_of_direct_engine_use_does_not_grow`. `application` же
звертається до `app.audit` за задумом, тож місце саме тут.
"""

from __future__ import annotations

from functools import lru_cache

from app.core.config import settings


@lru_cache(maxsize=1)
def engine_fingerprints() -> tuple[str, str]:
    """`(detector, scoring)` цього процесу.

    Імпорт усередині функції: реєстр чеків підтягується один раз, на
    першому запиті, а не на старті процесу. Сам реєстр заповнює
    `detector_version()`, тож окремий `import app.audit.checks` тут не
    потрібен — і не лише зайвий: у модулі, де `app` уже щось означає,
    він звʼязав би це імʼя з пакетом.
    """
    from app.audit.versions import detector_version, scoring_version

    return detector_version(), scoring_version()


def describe() -> dict[str, str]:
    """Опис складу процесу для `/health`.

    Рівно три рядки й жодних припущень: два відбитки з коду та коміт з
    оточення, якщо його передали.
    """
    detector, scoring = engine_fingerprints()
    return {
        "detector": detector,
        "scoring": scoring,
        "commit": settings.build_commit,
    }
